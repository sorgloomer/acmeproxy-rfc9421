// Command xacmeproxy builds an acmeproxy server with the libdns providers you
// choose, like xcaddy does for Caddy:
//
//	xacmeproxy build [--output file] --with <module>[@<version>][=<local dir>]...
//
// Each provider is registered under the last element of its module path
// (github.com/libdns/route53 -> "route53"). Passing the acmeproxy module
// itself with --with pins or replaces the server version.
package main

import (
	"fmt"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"strings"
)

const serverModule = "github.com/sorgloomer/acmeproxy-rfc9421"

type module struct{ path, version, replacement string }

func parseWith(s string) module {
	var m module
	s, m.replacement, _ = strings.Cut(s, "=")
	m.path, m.version, _ = strings.Cut(s, "@")
	if m.version == "" {
		m.version = "latest"
	}
	return m
}

// providerName derives the provider name from a module path, skipping a
// major version suffix: example.com/dns/v2 -> dns.
func providerName(modPath string) string {
	base := path.Base(modPath)
	if len(base) > 1 && base[0] == 'v' && strings.Trim(base[1:], "0123456789") == "" {
		base = path.Base(path.Dir(modPath))
	}
	return base
}

func generateMain(providers []module) string {
	var imports, registrations strings.Builder
	for i, p := range providers {
		fmt.Fprintf(&imports, "\tp%d %q\n", i, p.path)
		fmt.Fprintf(&registrations, "\tserver.RegisterProvider(%q, func() any { return new(p%d.Provider) })\n", providerName(p.path), i)
	}
	return "// Code generated by xacmeproxy. DO NOT EDIT.\npackage main\n\nimport (\n" +
		"\t\"" + serverModule + "/servers/golang/server\"\n" + imports.String() +
		")\n\nfunc main() {\n" + registrations.String() + "\tserver.Main()\n}\n"
}

func main() {
	if err := build(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "xacmeproxy:", err)
		os.Exit(1)
	}
}

func build(args []string) error {
	if len(args) == 0 || args[0] != "build" {
		return fmt.Errorf("usage: xacmeproxy build [--output file] --with <module>[@<version>][=<dir>]...")
	}
	server := module{path: serverModule, version: "latest"}
	var providers []module
	output := "acmeproxy"
	for i := 1; i < len(args); i++ {
		if i+1 >= len(args) {
			return fmt.Errorf("%s needs a value", args[i])
		}
		switch args[i] {
		case "--with":
			if m := parseWith(args[i+1]); m.path == serverModule {
				server = m
			} else {
				providers = append(providers, m)
			}
		case "--output":
			output = args[i+1]
		default:
			return fmt.Errorf("unknown argument %q", args[i])
		}
		i++
	}
	if len(providers) == 0 {
		return fmt.Errorf("add at least one --with <libdns provider module>")
	}
	output, _ = filepath.Abs(output)

	dir, err := os.MkdirTemp("", "xacmeproxy-*")
	if err != nil {
		return err
	}
	defer os.RemoveAll(dir)
	if err := os.WriteFile(filepath.Join(dir, "main.go"), []byte(generateMain(providers)), 0o644); err != nil {
		return err
	}
	commands := [][]string{{"mod", "init", "acmeproxy-custom"}}
	for _, m := range append([]module{server}, providers...) {
		if m.replacement != "" {
			abs, _ := filepath.Abs(m.replacement)
			commands = append(commands, []string{"mod", "edit", "-replace=" + m.path + "=" + abs,
				"-require=" + m.path + "@v0.0.0-00010101000000-000000000000"})
		} else {
			commands = append(commands, []string{"get", m.path + "@" + m.version})
		}
	}
	commands = append(commands, []string{"mod", "tidy"}, []string{"build", "-trimpath", "-o", output, "."})
	for _, c := range commands {
		fmt.Fprintln(os.Stderr, "go", strings.Join(c, " "))
		cmd := exec.Command("go", c...)
		cmd.Dir, cmd.Stdout, cmd.Stderr = dir, os.Stderr, os.Stderr
		if err := cmd.Run(); err != nil {
			return err
		}
	}
	fmt.Println("built", output)
	return nil
}
